"""Render docs/assets.md from the machine-readable asset records in docs/assets/.

The JSON files are exported from the delivery metadata of the released buildings:

* ``museum_assets.json``  - union of ``ASSET_LICENSES.json`` over the 29
  current museum deliveries (one row per source asset, with the buildings that
  use it).
* ``factory_assets.json`` - the user-confirmed industrial-hall asset credits plus the
  NVIDIA SimReady credit list written by the asset-library build.

Nothing here is redistributed: every row points at the upstream source, and the
assets themselves are downloaded by the generation scripts at run time.

    python tools/build_asset_catalog.py          # rewrites docs/assets.md
    python tools/build_asset_catalog.py --check  # exits 1 if docs/assets.md is stale
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "assets"
OUT = ROOT / "docs" / "assets.md"

LICENCE_URL = {
    "CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
    "CC0": "https://creativecommons.org/publicdomain/zero/1.0/",
    "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/",
}

SOURCE_HOME = {
    "Poly Haven": "https://polyhaven.com",
    "ambientCG": "https://ambientcg.com",
    "Smithsonian": "https://3d.si.edu",
    "Cleveland Museum of Art": "https://www.clevelandart.org/open-access",
    "MolmoSpaces": "https://huggingface.co/datasets/allenai/molmospaces",
    "NVIDIA simready-assets": "https://huggingface.co/datasets/nvidia/simready-assets",
    "NVIDIA Industrial Assets Pack": "https://docs.omniverse.nvidia.com/usd/latest/usd_content_samples/downloadable_packs.html",
    "NVIDIA Warehouse Assets Pack": "https://docs.omniverse.nvidia.com/usd/latest/usd_content_samples/downloadable_packs.html",
    "NVIDIA USD Explorer Sample": "https://docs.omniverse.nvidia.com/usd/latest/usd_content_samples/downloadable_packs.html",
}


def _cell(text: object) -> str:
    return str(text if text not in (None, "") else "-").replace("|", "\\|").replace("\n", " ")


def _link(label: str, url: str | None) -> str:
    return f"[{_cell(label)}]({url})" if url else _cell(label)


def museum_section(rows: list[dict]) -> list[str]:
    by_source: dict[str, list[dict]] = collections.defaultdict(list)
    for row in rows:
        source = row["source"] or "unknown"
        if source.startswith("Existing") and "ambientCG" in source:
            source = "ambientCG"
        by_source[source].append(row)
    third_party = {
        k: v for k, v in by_source.items() if not k.lower().startswith(("procedural", "museum29"))
    }
    procedural = {k: v for k, v in by_source.items() if k not in third_party}

    out = [
        "## Museums (29 buildings, 12 architectural styles)",
        "",
        f"{len(rows)} distinct asset records across the 29 current deliveries "
        f"({sum(len(v) for v in third_party.values())} third-party, "
        f"{sum(len(v) for v in procedural.values())} authored procedurally for this project).",
        "",
        "| Source | Assets | Licence | Used for |",
        "|---|---:|---|---|",
    ]
    for source, items in sorted(third_party.items(), key=lambda kv: -len(kv[1])):
        licences = sorted({i["license"] for i in items if i.get("license")})
        uses = collections.Counter(u for i in items for u in i.get("used_for") or [])
        use_text = ", ".join(u for u, _ in uses.most_common(6)) or "exhibits, props"
        lic = ", ".join(_link(code, LICENCE_URL.get(code)) for code in licences)
        out.append(
            f"| {_link(source, SOURCE_HOME.get(source))} | {len(items)} | {lic} | {_cell(use_text)} |"
        )
    for source, items in sorted(procedural.items()):
        out.append(
            f"| {_cell(source)} | {len(items)} | project-authored | procedural geometry, baked textures, original artwork |"
        )
    out += [
        "",
        "Architectural elements (door casings, panel doors, pillars, windows) come from",
        "[Infinigen](https://github.com/princeton-vl/infinigen)'s architectural factories (BSD-3-Clause);",
        "the five grand-staircase families are generated by `generation/museum/staircase_core.py`.",
        "",
    ]
    for source, items in sorted(third_party.items(), key=lambda kv: -len(kv[1])):
        out += [
            "<details>",
            f"<summary><b>{_cell(source)}</b> - all {len(items)} assets</summary>",
            "",
            "| Asset | Licence | Buildings |",
            "|---|---|---|",
        ]
        for item in sorted(items, key=lambda i: str(i["id"]).lower()):
            out.append(
                f"| {_link(item['id'], item.get('url'))} | {_cell(item.get('license'))} | "
                f"{_cell(' '.join(item.get('buildings') or []))} |"
            )
        out += ["", "</details>", ""]
    return out


def factory_section(data: dict) -> list[str]:
    confirmed = data["confirmed"]
    simready = data["simready"]
    eligible = [s for s in simready if s.get("status", "").strip() == "ELIGIBLE"]
    by_source = collections.Counter(a["source"] for a in confirmed)
    out = [
        "## Industrial halls (27 buildings, Round 4)",
        "",
        "| Source | Assets admitted to scenes | Licence |",
        "|---|---:|---|",
        f"| {_link('NVIDIA SimReady assets', SOURCE_HOME['NVIDIA simready-assets'])} | "
        f"{len(eligible)} eligible of {len(simready)} processed | "
        f"{_link('CC-BY-4.0', LICENCE_URL['CC-BY-4.0'])} (attribution: NVIDIA) |",
    ]
    licence_of = {
        "MolmoSpaces": "per-object Objaverse licence (CC-BY family, recorded per asset)",
        "Procedural project-authored": "project-authored",
    }
    for source, count in by_source.most_common():
        licence = licence_of.get(
            source, "NVIDIA Omniverse licence terms (research use; not redistributed)"
        )
        out.append(f"| {_link(source, SOURCE_HOME.get(source))} | {count} | {licence} |")
    out += [
        "",
        'SimReady credits, as required by CC-BY-4.0: *"NVIDIA simready-assets", NVIDIA,',
        "<https://huggingface.co/datasets/nvidia/simready-assets>, licensed under CC-BY-4.0.*",
        "Project changes: source-unit and axis normalisation, rigid ground alignment, explicit static",
        "collision proxies, original dynamic physics disabled.",
        "",
        "<details>",
        f"<summary><b>NVIDIA SimReady</b> - all {len(simready)} processed assets</summary>",
        "",
        "| Asset | Status |",
        "|---|---|",
    ]
    for s in sorted(simready, key=lambda s: s["asset_id"]):
        out.append(f"| {_link(s['asset_id'], s.get('url'))} | {_cell(s.get('status'))} |")
    out += [
        "",
        "</details>",
        "",
        "<details>",
        f"<summary><b>Other industrial-hall assets</b> - all {len(confirmed)} user-confirmed assets</summary>",
        "",
        "| Asset | Source | Class | Licence record |",
        "|---|---|---|---|",
    ]
    for a in sorted(confirmed, key=lambda a: (a["source"], a["asset_id"])):
        lic = (
            a.get("license_code_from_API")
            or a.get("license_code_from_metadata")
            or a.get("license_bucket")
        )
        out.append(
            f"| {_link(a['asset_id'], a.get('asset_original_url'))} | {_cell(a['source'])} | "
            f"{_cell(a.get('user_class'))} | {_cell(lic)} |"
        )
    out += ["", "</details>", ""]
    return out


def render() -> str:
    museum = json.loads((DATA / "museum_assets.json").read_text(encoding="utf-8"))
    factory = json.loads((DATA / "factory_assets.json").read_text(encoding="utf-8"))
    head = [
        "# Assets and data sources",
        "",
        "<!-- Generated by tools/build_asset_catalog.py from docs/assets/*.json. Do not edit by hand. -->",
        "",
        "No third-party scene, model, texture or HDRI is redistributed in this repository.",
        "The generation scripts download each asset from its upstream source at run time;",
        "this page records what was used, where it came from and under which licence.",
        "",
        "## Shared across all building types",
        "",
        "| Component | Role | Licence |",
        "|---|---|---|",
        "| [MolmoSpaces](https://huggingface.co/datasets/allenai/molmospaces) (Allen Institute for AI) | single-storey source scenes for the residential and stacked-factory buildings; object packages for Factory80 | see the dataset card; per-object licences recorded |",
        "| [Infinigen](https://github.com/princeton-vl/infinigen) (Princeton VL) | staircase factories (straight / L / U) for residential and factory; architectural factories (doors, casings, pillars, windows) for museums | BSD-3-Clause |",
        "| [Blender](https://www.blender.org) `bpy` | runtime for Infinigen and for museum authoring | GPL-2.0-or-later (tool, not vendored) |",
        "| [NVIDIA Isaac Sim](https://developer.nvidia.com/isaac/sim) / PhysX / RTX | collision validation (C2, C5) and path-traced photographs | NVIDIA software licence (tool, not vendored) |",
        "| [NVIDIA ProtoMotions](https://github.com/NVlabs/ProtoMotions) | scene-geometry cache, standability and SceneLib packaging | Apache-2.0 |",
        "| [OpenUSD](https://github.com/PixarAnimationStudios/OpenUSD) | scene description for every delivery | Apache-2.0 (modified) |",
        "",
    ]
    return "\n".join(head + museum_section(museum) + factory_section(factory)) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if docs/assets.md is out of date"
    )
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/assets.md is stale; run tools/build_asset_catalog.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
